#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const repoRoot = path.resolve(__dirname, "..");
const packageJsonPath = path.join(repoRoot, "package.json");
const databaseJsonPath = path.join(repoRoot, "public", "d4dad.json");
const outputPath = path.join(
  repoRoot,
  "src",
  "config",
  "build-info.generated.ts",
);

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function parseVersion(version) {
  const match = /^(\d+)\.(\d+)\.(\d+)(?:[-+].*)?$/.exec(version);

  if (!match) {
    throw new Error(`Invalid package version: ${version}`);
  }

  return {
    major: Number(match[1]),
    minor: Number(match[2]),
    revision: Number(match[3]),
  };
}

function createBuildInfo({ databaseVersion, siteVersion }) {
  return {
    databaseVersion,
    siteVersion,
    version: parseVersion(siteVersion),
  };
}

function renderBuildInfoModule(buildInfo) {
  const { major, minor, revision } = buildInfo.version;

  return `// This file is generated by scripts/generate-build-info.cjs.
// Do not edit it manually.

const DATABASE_VERSION = ${JSON.stringify(buildInfo.databaseVersion)};
const SITE_VERSION = ${JSON.stringify(buildInfo.siteVersion)};
const VERSION = { major: ${major}, minor: ${minor}, revision: ${revision} };

export { DATABASE_VERSION, SITE_VERSION, VERSION };
`;
}

function writeBuildInfo(output, buildInfo) {
  fs.writeFileSync(output, renderBuildInfoModule(buildInfo), "utf8");
}

function main() {
  const packageJson = readJson(packageJsonPath);
  const databaseJson = readJson(databaseJsonPath);

  if (
    typeof packageJson.version !== "string" ||
    packageJson.version.length === 0
  ) {
    throw new Error("package.json is missing a valid version.");
  }

  if (
    typeof databaseJson.buildVersion !== "string" ||
    databaseJson.buildVersion.length === 0
  ) {
    throw new Error("public/d4dad.json is missing a valid buildVersion.");
  }

  const buildInfo = createBuildInfo({
    databaseVersion: databaseJson.buildVersion,
    siteVersion: packageJson.version,
  });

  writeBuildInfo(outputPath, buildInfo);
  console.log(
    `[build-info] Wrote ${path.relative(repoRoot, outputPath)} ` +
      `(site ${buildInfo.siteVersion}, database ${buildInfo.databaseVersion})`,
  );
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(
      `[build-info] ${error instanceof Error ? error.message : String(error)}`,
    );
    process.exit(1);
  }
}

module.exports = {
  createBuildInfo,
  parseVersion,
  renderBuildInfoModule,
};
